"""Generates the Replaybox launcher banner and adaptive icon (piste A) as Android vector drawables.

Usage: python -I make_logo.py <Manrope.ttf> <res dir>
"""
import math
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

GROUND = "#FF0E1013"
TEXT = "#FFF3F4F6"
AMBER = "#FFF2B544"


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def replay_symbol(cx, cy, r, w):
    """Same geometry as the approved web mock: arc with a gap at the top, head at top-right."""
    def pt(deg):
        a = math.radians(deg)
        return cx + r * math.cos(a), cy + r * math.sin(a)

    sx, sy = pt(-112)
    ex, ey = pt(-62)
    a = math.radians(-62)
    d = (math.sin(a), -math.cos(a))
    perp = (-d[1], d[0])
    h = w * 1.25
    tip = (ex + d[0] * h * 1.3, ey + d[1] * h * 1.3)
    b1 = (ex + perp[0] * h, ey + perp[1] * h)
    b2 = (ex - perp[0] * h, ey - perp[1] * h)
    t = r * 0.42
    arc = f"M{f(sx)},{f(sy)} A{f(r)},{f(r)} 0 1 0 {f(ex)},{f(ey)}"
    head = f"M{f(tip[0])},{f(tip[1])} L{f(b1[0])},{f(b1[1])} L{f(b2[0])},{f(b2[1])} Z"
    play = f"M{f(cx - t * 0.7)},{f(cy - t)} L{f(cx + t * 1.05)},{f(cy)} L{f(cx - t * 0.7)},{f(cy + t)} Z"
    return f"""    <path
        android:pathData="{arc}"
        android:strokeColor="{AMBER}"
        android:strokeWidth="{f(w)}"
        android:strokeLineCap="round" />
    <path
        android:pathData="{head}"
        android:fillColor="{AMBER}"
        android:strokeColor="{AMBER}"
        android:strokeWidth="1.5"
        android:strokeLineJoin="round" />
    <path
        android:pathData="{play}"
        android:fillColor="{TEXT}"
        android:strokeColor="{TEXT}"
        android:strokeWidth="2"
        android:strokeLineJoin="round" />
"""


def text_path(font, text, x, baseline, size, tracking):
    upem = font["head"].unitsPerEm
    scale = size / upem
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    parts = []
    pen_x = x
    for ch in text:
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, pen_x, baseline)))
        parts.append(pen.getCommands())
        pen_x += hmtx[name][0] * scale + tracking
    return " ".join(p for p in parts if p), pen_x - tracking


def vector(width, height, body):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by make_logo.py (piste A « Reprise », chosen 2026-11-07). Wordmark: Manrope ExtraBold, SIL OFL 1.1. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{width}dp"
    android:height="{height}dp"
    android:viewportWidth="{width}"
    android:viewportHeight="{height}">
{body}</vector>
"""


def main():
    font = TTFont(sys.argv[1])
    font = instancer.instantiateVariableFont(font, {"wght": 800})
    res = Path(sys.argv[2])

    word, end = text_path(font, "Replaybox", 124, 101, 31, -0.6)
    banner = f"""    <path
        android:pathData="M0,0h320v180h-320z"
        android:fillColor="{GROUND}" />
{replay_symbol(74, 90, 30, 8)}    <path
        android:pathData="{word}"
        android:fillColor="{TEXT}" />
"""
    (res / "drawable" / "ic_banner.xml").write_text(vector(320, 180, banner), encoding="utf-8", newline="\n")

    # Adaptive icon foreground: symbol centred in the 66 dp safe zone of the 108 dp canvas.
    (res / "drawable" / "ic_launcher_foreground.xml").write_text(
        vector(108, 108, replay_symbol(54, 55, 21, 6.5)), encoding="utf-8", newline="\n")
    print(f"wordmark ends at x={end:.1f} of 320")


main()
